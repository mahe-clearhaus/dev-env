#!/usr/bin/env bash
# Dump the macOS settings this repo tracks into ./ , ready to commit.
# Re-run after changing anything in System Settings, then `git diff` to see it.
set -euo pipefail
cd "$(dirname "$0")"

# ---------------------------------------------------------------- app shortcuts
# System Settings > Keyboard > Keyboard Shortcuts > App Shortcuts. Each override
# lives as NSUserKeyEquivalents in the app's own domain, keyed by the exact menu
# item title. Emitted as a re-runnable script because that diffs far better than
# a plist and doubles as the apply step.
{
  echo '#!/usr/bin/env bash'
  echo '# GENERATED by export.sh -- do not edit; change it in System Settings and re-export.'
  echo '# App Shortcuts (System Settings > Keyboard > Keyboard Shortcuts > App Shortcuts).'
  echo '# Key syntax: @ cmd  ~ opt  ^ ctrl  $ shift.  A bare modifier combo unbinds by'
  echo '# moving the item out of the way rather than removing it.'
  echo 'set -euo pipefail'
  echo
  for f in "$HOME"/Library/Preferences/*.plist \
           "$HOME"/Library/Containers/*/Data/Library/Preferences/*.plist; do
    [ -f "$f" ] || continue
    domain=$(basename "$f" .plist)
    /usr/libexec/PlistBuddy -c "Print :NSUserKeyEquivalents" "$f" >/dev/null 2>&1 || continue
    # Skip domains where the dict exists but is empty.
    plutil -convert xml1 -o - "$f" 2>/dev/null | python3 -c "
import sys, plistlib, shlex
d = plistlib.loads(sys.stdin.buffer.read()).get('NSUserKeyEquivalents') or {}
if d:
    print('# ' + '$domain')
    for item, key in sorted(d.items()):
        print('defaults write %s NSUserKeyEquivalents -dict-add %s %s'
              % (shlex.quote('$domain'), shlex.quote(item), shlex.quote(key)))
    print()
"
  done
} > app-shortcuts.sh
chmod +x app-shortcuts.sh

# ------------------------------------------------------------ system shortcuts
# System Settings > Keyboard > Keyboard Shortcuts > everything else (Mission
# Control, Spotlight, Screenshots, input sources, spaces...). One opaque domain
# keyed by numeric action id, so it is copied wholesale as XML.
#
# NOTE: read the plist directly rather than via `defaults export`. cfprefsd
# refuses this domain to a terminal without Full Disk Access -- `defaults read
# com.apple.symbolichotkeys` reports "does not exist" while the file is right
# there. Reading the file avoids depending on that grant.
HOTKEYS="$HOME/Library/Preferences/com.apple.symbolichotkeys.plist"
if [ -f "$HOTKEYS" ]; then
  plutil -convert xml1 -o symbolichotkeys.plist "$HOTKEYS"
else
  echo "warning: $HOTKEYS missing; no system shortcuts have been customised" >&2
fi

# ...plus a readable rendering, purely so `git diff` is interpretable.
python3 - <<'PY' > symbolichotkeys.txt
import plistlib
MODS = [(1 << 17, 'shift'), (1 << 18, 'ctrl'), (1 << 19, 'opt'),
        (1 << 20, 'cmd'), (1 << 23, 'numpad/fn')]
with open('symbolichotkeys.plist', 'rb') as fh:
    keys = plistlib.load(fh).get('AppleSymbolicHotKeys', {})
print('GENERATED by export.sh -- readable rendering of symbolichotkeys.plist.')
print('id  = macOS action id (opaque; see README.md)')
print('key = [character, keycode, modifier mask]; 65535 means unset')
print()
for k in sorted(keys, key=int):
    v = keys[k]
    params = v.get('value', {}).get('parameters')
    if params:
        names = '+'.join(n for bit, n in MODS if params[2] & bit) or 'none'
        desc = '%s  char=%s keycode=%s' % (names, params[0], params[1])
    else:
        desc = '(no binding stored)'
    print('%4s  enabled=%-5s  %s' % (k, v.get('enabled'), desc))
PY

echo "exported: app-shortcuts.sh, symbolichotkeys.plist, symbolichotkeys.txt"
